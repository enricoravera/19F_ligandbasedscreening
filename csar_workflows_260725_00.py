# Workflow 3: Reporter assay
# ============================================================================

def workflow_reporter(
    reporter_name: str,
    reporter_signal_free: float,
    reporter_signal_protein: float,
    compounds: List[CompoundData],
) -> WorkflowResult:
    """
    Reporter assay affinity ranking (Fig. 7, Rüdisser 2020).

    The reporter signal is measured in the presence of each test compound.
    Displacement of the reporter is proportional to relative binding affinity.

    Parameters
    ----------
    reporter_name : str
        Name of the reporter ligand.
    reporter_signal_free : float
        Intensity of the reporter signal WITHOUT protein.
    reporter_signal_protein : float
        Intensity of the reporter signal WITH protein (no competitor).
    compounds : list of CompoundData
        Each compound must have ``reporter_signal_plus`` set to the
        intensity of the reporter in the presence of BOTH protein and that
        compound.  ``reporter_signal_minus`` is unused here.

    Returns
    -------
    WorkflowResult
        ``scores`` encodes degree of displacement (higher = stronger binder).
    """
    # Reference: fractional reporter signal in presence of protein (no competitor)
    I_ref = reporter_signal_protein / reporter_signal_free  # ~0.2 in the paper

    names, scores_list = [], []
    for c in compounds:
        if c.reporter_signal_plus is None:
            warnings.warn(f"Compound {c.name}: reporter_signal_plus not set — skipping.")
            continue
        I_comp = c.reporter_signal_plus / reporter_signal_free
        # Displacement = how much the reporter recovers toward the free signal
        # 0 = no displacement (same as with protein only), 1 = full displacement
        displacement = max((I_comp - I_ref) / (1.0 - I_ref), 0.0)
        names.append(c.name)
        scores_list.append(displacement)

    scores = np.array(scores_list)
    s_max = scores.max() if scores.max() > 0 else 1.0

    notes = [
        f"Reporter: {reporter_name}, I_free={reporter_signal_free:.3f}, "
        f"I_protein={reporter_signal_protein:.3f} (fraction={I_ref:.3f})"
    ]
    return WorkflowResult(
        workflow="Reporter",
        compound_names=names,
        scores=scores / s_max,
        notes=notes,
    )


# ============================================================================
# Workflow 4: Exchange-suppressed ligand-observed titration (Eq. 12)
# ============================================================================

def workflow_titration(
    compounds: List[CompoundData],
    B: float,
    protein_concentrations: np.ndarray,
    ligand_concentration: float,
    tau_c: float,
    nucleus: str = "19F",
    n_sites: int = 1,
    fit_KD: bool = False,
    fit_R2free: bool = False,
    protein_name: Optional[str] = None,
    protein_MW_kDa: float = 23.0,
    experiment_type: str = "s",
) -> WorkflowResult:
    """
    Exchange-suppressed ligand-observed titration (Fig. 8, Rüdisser 2020).

    Each compound in ``compounds`` must have relaxation_data[B] set as a
    2-D array: rows = protein concentrations (same order as
    ``protein_concentrations``), columns = (delays, intensities).
    Alternatively, if R2_fitted[B] is a list of (R2_free, R2_prot) tuples
    per protein concentration, those are used directly.

    Per-concentration R2 uncertainties are used when available: if
    ``c.R2_err[B]`` is a list of σ_R2 values (one per concentration,
    matching the order of ``protein_concentrations``), they are shown as
    error bars in the binding isotherm figure and, when all values are
    finite and positive, they are passed as inverse-variance weights to
    the KD fit via ``lmfit.Model.fit``.  If uncertainties are missing or
    invalid the plot falls back to a plain scatter and the fit uses
    unweighted least-squares.

    Parameters
    ----------
    compounds : list of CompoundData
        relaxation_data[B] should be a list of (delays, intensities) arrays,
        one per protein concentration.  Or R2_fitted[B] = list of R2 values
        at each [P].  Per-concentration 1σ uncertainties may optionally be
        stored in R2_err[B] as a list of the same length.
    B : float
        Magnetic field in Tesla.
    protein_concentrations : array-like
        Protein concentrations in µM (same order as data in each compound).
    ligand_concentration : float
        Total ligand concentration in µM.
    tau_c : float
        Rotational correlation time of the complex (s).
    nucleus : str
        Observed nucleus.
    n_sites : int
        Number of equivalent binding sites (default 1).
    fit_KD : bool
        If True, attempt to fit KD from Eq. 12.  This is ill-conditioned
        for weak binders (see Discussion) — a warning is emitted.
    fit_R2free : bool
        If True, let R2,f float as a third fit parameter instead of
        fixing it at the value measured at [P]=0 (the default). R2,f is
        directly measurable, and fixing it is precisely what reduces
        Eq. 12 from three free parameters (KD, R2,b, R2,f) down to two
        — the whole point of the exchange-suppressed approach in this
        paper. Freeing it again reopens a third degree of freedom on
        top of the KD/R2,b degeneracy that's already ill-conditioned,
        so this is OFF by default and should only be turned on if the
        single [P]=0 measurement is suspected to be unrepresentative
        (e.g. noisy, or recorded under slightly different conditions
        than the titration points). To avoid trading one degeneracy for
        two, R2,f is still bounded to within ±50% of the measured value
        (not fully unconstrained) and its fitted value is reported in
        the isotherm figure legend and in ``notes`` — it is not just
        silently substituted for the fixed value elsewhere in the
        codebase, so check ``notes`` for a fitted-vs-measured comparison
        when using this option.
    protein_name : str, optional
        Used to namespace the binding isotherm figures under
        ``fit_results/{protein_name}/`` — same convention as the per-compound
        fit figures produced by ``populate_config.py``.
    protein_MW_kDa : float
        Protein molecular weight (kDa), used only to compute the
        rule-of-thumb dipolar relaxation R₂,DD,b ≈ protein_MW_kDa
        (same approximation as ``workflow_FastCSAR``). The fitted bound
        R₂,b (``fit_KD=True``) is capped at 20× this value, since an
        unconstrained fit can otherwise converge on a dipolar
        contribution that is physically implausible for the protein's
        size; the fitted KD itself is bounded away from exactly zero
        (lower limit 1e-9 M) to keep the optimizer well-defined.
    experiment_type : str
        ``"s"`` (selective, default) or ``"n"`` (non-selective /
        J-modulated) — selects between :func:`filter_outliers_fit_R2`'s
        two internal models when fitting raw ``relaxation_data`` (i.e.
        when a compound doesn't already carry pre-fitted R2 values in
        ``R2_fitted``). Matches the same convention used throughout
        ``populate_config.py``.

    Returns
    -------
    WorkflowResult
        ``scores`` = slope of R₂ vs [P] (normalised).
        ``KD_estimates`` = fitted KD in µM if fit_KD=True, else None.
    """
    prot_arr = np.asarray(protein_concentrations, dtype=float)  # µM
    L_tot = ligand_concentration   # µM
    basedir = _basedir(protein_name, run_field=B)
    # Rule-of-thumb dipolar contribution (bound state) — same
    # approximation used in workflow_FastCSAR.
    R2_DD_b_rule = protein_MW_kDa
    # Upper bound of R2_DD_b is the maximum density of protons around the fluorine nucleus, which is roughly 5× the rule-of-thumb value.
    R2_DD_b_rule_upper = 5 * R2_DD_b_rule

    names, slopes, KD_fits, KD_errs = [], [], [], []
    notes = []
    use_Jmod = (experiment_type == "n")

    for c in compounds:
        # Per-point R2 uncertainties from the outlier-masked fit below
        # (relaxation_data branch only) — None unless that branch runs.
        R2_err_from_fit: Optional[np.ndarray] = None

        # Collect R2 values at each protein concentration
        if isinstance(c.R2_fitted.get(B), list):
            R2_vals = np.array([r for r in c.R2_fitted[B]], dtype=float)
        elif B in c.relaxation_data and isinstance(c.relaxation_data[B], list):
            R2_vals, R2_errs_local = [], []
            for delays_i, intensities_i in c.relaxation_data[B]:
                delays_i = np.asarray(delays_i, dtype=float)
                intensities_i = np.asarray(intensities_i, dtype=float)
                # Same outlier-masked fit populate_config.py uses (see its
                # fit_experiment, titration branch) instead of a plain,
                # unmasked lmfit fit — one fitting path for raw
                # relaxation data across both scripts.
                mask, result, _A, _a = filter_outliers_fit_R2(
                    delays_i, intensities_i, multi=1, use_Jmod=use_Jmod
                )
                r2_i, sigma_r2_i = extract_R2_uncertainty(result, multi=1)
                R2_vals.append(r2_i)
                R2_errs_local.append(sigma_r2_i)
            R2_vals = np.array(R2_vals)
            R2_err_from_fit = np.array(R2_errs_local)
        else:
            warnings.warn(f"Compound {c.name}: titration data not found — skipping.")
            continue

        # Collect per-concentration R2 uncertainties if available.
        # A list of matching length is used for error bars; additionally,
        # all values must be finite and positive for the weighted KD fit.
        # The outlier-masked fit above already gives per-point sigma_R2
        # when relaxation_data was used; only fall back to c.R2_err (the
        # pre-fitted-R2_fitted path) if that wasn't the case.
        if R2_err_from_fit is not None and len(R2_err_from_fit) == len(R2_vals):
            R2_err_vals: Optional[np.ndarray] = R2_err_from_fit
        else:
            R2_err_raw = c.R2_err.get(B)
            R2_err_vals = None
            if isinstance(R2_err_raw, list) and len(R2_err_raw) == len(R2_vals):
                R2_err_vals = np.array(R2_err_raw, dtype=float)
        # Separate flag: are the uncertainties usable as fit weights?
        # Requires all entries to be strictly positive and finite —
        # non-positive or NaN values would produce infinite weights and
        # break the optimiser. Fall back to unweighted if any are bad.
        use_weighted_fit = (
            R2_err_vals is not None
            and bool(np.all(np.isfinite(R2_err_vals)))
            and bool(np.all(R2_err_vals > 0))
        )

        R2_free_measured = R2_vals[0] if prot_arr[0] == 0.0 else R2_vals.min()

        # --- Ranking by slope (R2 / [P]) as in the paper ---
        # Use simple linear regression of R2 vs [P] for robustness
        slope, _ = np.polyfit(prot_arr, R2_vals, 1)
        names.append(c.name)
        slopes.append(slope)

        # KD fit (optional) — keep the closures inside the compound loop
        # so R2_free_measured is captured correctly for each compound.
        fitted_KD = np.nan
        fitted_R2b = np.nan
        fitted_R2free = np.nan
        err_KD = np.nan
        err_R2b = np.nan
        err_R2free = np.nan
        R2_CSA_b = R2_CSA_bound(c.delta_sigma, c.eta, B, tau_c, nucleus)
        #this should be the dominant term in the bound state, so we can use it to estimate a reasonable starting point for R2_b.
        R2_b_guess = R2_DD_b_rule + R2_CSA_b
        if fit_KD:
            # Eq. 12:  R2_SL = R2_f + n·[P]_tot·(R2_b − R2_f) / (KD + [L]_f) · [L]_f/[L]_tot
            # Simplified assuming [L]_f ≈ [L]_tot (p_b << 1)
            if fit_R2free:
                # R2_free itself becomes a third fit parameter here,
                # rather than the fixed measured value used below.
                def titration_eq(P_tot, KD, R2_b, R2_free):
                    Lf = L_tot  # approximation
                    return R2_free + n_sites * P_tot * (R2_b - R2_free) / (KD + Lf)
            else:
                def titration_eq(P_tot, KD, R2_b):
                    Lf = L_tot  # approximation
                    return R2_free_measured + n_sites * P_tot * (R2_b - R2_free_measured) / (KD + Lf)
            # Upper bound on R2_b:  KD and R2_b trade off against
            # each other almost perfectly (a larger KD can always be
            # compensated by a larger R2_b, and vice versa — exactly the
            # degeneracy the paper itself reports in the Discussion), so
            # the optimizer is free to run R2_b up to unphysical values while
            # KD swings wildly between fits. Capping R2_b breaks that
            # degeneracy and is what keeps both parameters well-behaved.
            R2_b_upper = R2_DD_b_rule_upper + R2_CSA_b * 5.0
            # Guard against the edge case where R2_free itself already
            # exceeds that cap (the lower bound passed to the fit),
            # which would make the bounds invalid (lower > upper).
            if R2_b_upper <= R2_free_measured:
                R2_b_upper = R2_free_measured * (1.0 + 1e-6)
                notes.append(
                    f"{c.name}: R2_free already exceeds the rule-of-thumb + CSA limit"
                    f" R2_b upper bound relaxed slightly "
                    f"above R2_free instead."
                )
            #Guard against the edge case where R2_b_upper is less than 20x the last R2 value of the titration.
            if R2_b_upper <= R2_vals[-1]*20:
                R2_b_upper = R2_vals[-1]*20
                notes.append(
                    f"{c.name}: R2_b upper bound relaxed to 20x the last R2 value of the titration."
                )
            # p0 must lie strictly within [lower, upper] or the fit
            # raises immediately — clamp the naive "10x free" guess.
            #R2_b_p0 = min(R2_free_measured * 10.0, R2_b_upper * 0.9)
            R2_b_p0 = min(R2_b_guess, R2_b_upper * 0.9)
            R2_b_p0 = max(R2_b_p0, R2_free_measured * (1.0 + 1e-9))

            # Build an lmfit Model directly from the titration_eq closure —
            # its signature (P_tot, KD, R2_b[, R2_free]) already matches
            # what lmfit expects, with P_tot as the one independent variable.
            model = lmfit.Model(titration_eq, independent_vars=["P_tot"])
            params = model.make_params(KD=500.0, R2_b=R2_b_p0)
            # KD is bounded away from exactly zero (not 0.0) so the
            # optimizer's Jacobian near KD=0 stays well-defined; R2_b is
            # capped at R2_b_upper (see above).
            params["KD"].set(min=1e-3, max=1e5)
            params["R2_b"].set(min=R2_free_measured, max=R2_b_upper)
            if fit_R2free:
                # R2_free is bounded to ±50% of the measured value rather
                # than left fully free — R2,f is directly measurable, and
                # letting it roam unconstrained would reopen a third
                # degree of freedom on top of the KD/R2_b degeneracy this
                # function already has to guard against above. This just
                # allows the fit to compensate for a noisy/unrepresentative
                # single [P]=0 measurement, not to re-derive R2,f from
                # scratch.
                R2_free_lower = max(R2_free_measured * 0.5, 1e-6)
                R2_free_upper = R2_free_measured * 1.5
                params.add("R2_free", value=R2_free_measured,
                           min=R2_free_lower, max=R2_free_upper)

            # lmfit weights the residual directly by `weights` (not by a
            # sigma it divides by internally), so pass 1/σ — equivalent to
            # equivalent weighting to scipy's sigma+absolute_sigma=True.
            weights = 1.0 / R2_err_vals if use_weighted_fit else None

            fit_result = model.fit(
                R2_vals, params, P_tot=prot_arr, weights=weights,
                max_nfev=10000,
            )

            if fit_result.success:
                fitted_KD  = fit_result.params["KD"].value
                fitted_R2b = fit_result.params["R2_b"].value
                # stderr is None if lmfit couldn't estimate the covariance
                # (e.g. a parameter pinned at its bound) — report NaN then,
                # same as the previous np.sqrt(diag(pcov)) would effectively
                # need to, rather than letting a None through.
                err_KD  = fit_result.params["KD"].stderr
                err_KD  = err_KD if err_KD is not None else np.nan
                err_R2b = fit_result.params["R2_b"].stderr
                err_R2b = err_R2b if err_R2b is not None else np.nan
                if fit_R2free:
                    fitted_R2free = fit_result.params["R2_free"].value
                    err_R2free = fit_result.params["R2_free"].stderr
                    err_R2free = err_R2free if err_R2free is not None else np.nan
                    notes.append(
                        f"{c.name}: fitted R2,f = {fitted_R2free:.2f} s⁻¹ vs. "
                        f"{R2_free_measured:.2f} s⁻¹ measured at [P]=0."
                    )
                KD_fits.append(fitted_KD)
                KD_errs.append(err_KD)
            else:
                KD_fits.append(np.nan)
                KD_errs.append(np.nan)
                notes.append(
                    f"KD fit did not converge for {c.name}: {fit_result.message}"
                )

        # --- Binding isotherm figure ---
        fig_iso, ax_iso = plt.subplots(figsize=(5, 4))
        if R2_err_vals is not None:
            # Error bars from per-concentration R2 uncertainties.
            # matplotlib tolerates NaN in yerr (those caps are simply not drawn).
            ax_iso.errorbar(
                prot_arr, R2_vals, yerr=R2_err_vals,
                fmt="o", color="royalblue", zorder=3,
                capsize=3, capthick=1, elinewidth=1,
                label="Data",
            )
        else:
            ax_iso.scatter(prot_arr, R2_vals, color="royalblue", zorder=3, label="Data")
        title_iso = f"{c.name}  |  B = {B:.4g} T"
        if fit_KD and not np.isnan(fitted_KD):
            P_dense = np.linspace(prot_arr.min(), prot_arr.max(), 300)
            if fit_R2free:
                R2_fit_dense = titration_eq(P_dense, fitted_KD, fitted_R2b, fitted_R2free)
                fit_label = (f"Fit: KD = {_format_KD(fitted_KD)}, R₂,b = {fitted_R2b:.2f} ± {err_R2b:.2f} s⁻¹, "
                             f"R₂,f = {fitted_R2free:.2f} s⁻¹")
            else:
                R2_fit_dense = titration_eq(P_dense, fitted_KD, fitted_R2b)
                fit_label = f"Fit: KD = {_format_KD(fitted_KD)}, R₂,b = {fitted_R2b:.2f} ± {err_R2b:.2f} s⁻¹"
            ax_iso.plot(
                P_dense, R2_fit_dense, "r-",
                label=fit_label,
            )
        ax_iso.set_xlabel("[Protein] (µM)")
        ax_iso.set_ylabel("R₂ (s⁻¹)")
        ax_iso.set_title(title_iso, fontsize=10)
        ax_iso.legend(fontsize=8)
        ax_iso.spines[["top", "right"]].set_visible(False)
        fig_iso.tight_layout()
        iso_path = basedir / f"titration_isotherm_{_sanitize_dirname(c.name)}.png"
        fig_iso.savefig(iso_path, dpi=150, bbox_inches="tight")
        print(f"[plot] Saved binding isotherm to {iso_path}")
        plt.close(fig_iso)

    slopes_arr = np.array(slopes)
    s_max = slopes_arr.max() if slopes_arr.max() > 0 else 1.0
    scores = slopes_arr / s_max

    if fit_KD:
        warnings.warn(
            "KD fitting from ligand-observed titrations is ill-conditioned "
            "for weak binders (large KD/R2_b co-variance). "
            "Use slope ranking as primary output.",
            UserWarning,
        )
        notes.append(
            "KD values carry large uncertainty (see Rüdisser 2020, Discussion)."
        )

    return WorkflowResult(
        workflow="Titration",
        compound_names=names,
        scores=scores,
        KD_estimates=np.array(KD_fits) if KD_fits else None,
        KD_uncertainties=np.array(KD_errs) if KD_errs else None,
        notes=notes,
    )


