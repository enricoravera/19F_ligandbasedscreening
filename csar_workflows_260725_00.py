def plot_ranking(result: WorkflowResult, output_path: Optional[str] = None,
                 protein_concentration: Optional[float] = None) -> None:
    """
    Bar chart of affinity ranking from any workflow result.

    Parameters
    ----------
    result : WorkflowResult
    output_path : str, optional
        If given, save figure to this path instead of displaying.
    protein_concentration : float, optional
        Protein concentration in µM for ``csar``/``fastcsar`` workflows;
        included in the figure title when provided.
    """
    n = len(result.compound_names)
    order = np.argsort(result.scores)[::-1]
    names_sorted  = [result.compound_names[i] for i in order]
    scores_sorted = result.scores[order]

    fig, ax = plt.subplots(figsize=(max(6, n * 0.7), 4))
    colors = plt.cm.viridis(np.linspace(0.2, 0.85, n))

    # Error bars on the normalised score axis (σ_score = σ_p_b / p_b_max)
    yerr = None
    if result.pb_uncertainties is not None:
        yerr = result.pb_uncertainties[order]
        # Cap bars so they never extend below 0
        yerr_lo = np.minimum(yerr, scores_sorted)
        yerr = np.array([yerr_lo, yerr])

    bars = ax.bar(range(n), scores_sorted, color=colors, edgecolor="white",
                  linewidth=0.8, yerr=yerr,
                  error_kw=dict(ecolor="0.3", capsize=3, linewidth=1.2))

    if result.pb_estimates is not None:
        pb_sorted = result.pb_estimates[order]
        for bar, pb in zip(bars, pb_sorted):
            ax.text(
                bar.get_x() + bar.get_width() / 2,
                bar.get_height() + 0.01,
                f"{pb*100:.1f}%",
                ha="center", va="bottom", fontsize=7, color="0.3",
            )

    if result.KD_estimates is not None:
        KD_sorted = result.KD_estimates[order]
        for bar, kd in zip(bars, KD_sorted):
            if not np.isnan(kd):
                ax.text(
                    bar.get_x() + bar.get_width() / 2,
                    bar.get_height() / 2,
                    f"KD≈{_format_KD(kd)}",
                    ha="center", va="center", fontsize=6.5,
                    color="black", fontweight="bold",
                )

    ax.set_xticks(range(n))
    ax.set_xticklabels(names_sorted, rotation=40, ha="right", fontsize=9)
    ax.set_ylabel("Relative affinity (normalised score)", fontsize=9)
    title = f"{result.workflow} affinity ranking"
    if protein_concentration is not None:
        title += f"  ([Protein] = {protein_concentration:.6g} µM)"
    ax.set_title(title, fontsize=11, fontweight="bold")
    ax.yaxis.set_major_formatter(ticker.PercentFormatter(xmax=1))
    ax.set_ylim(0, 1.15)
    ax.spines[["top", "right"]].set_visible(False)

    if result.notes:
        fig.text(0.01, 0.01, " | ".join(result.notes), fontsize=6, color="0.5",
                 wrap=True, va="bottom")

    fig.tight_layout(rect=[0, 0.04, 1, 1])

    if output_path:
        fig.savefig(output_path, dpi=150, bbox_inches="tight")
        print(f"[plot] Saved ranking to {output_path}")
    else:
        plt.show()
    plt.close(fig)


def plot_CSA_isolation(
    result: WorkflowResult,
    output_path: Optional[str] = None,
    protein_concentration: Optional[float] = None,
) -> None:
    """
    Reproduce the "isolation of CSA effect" diagnostic — Fig. 4c,
    Rüdisser et al. 2020 (J Biomol NMR) — for every compound in a CSAR
    or FastCSAR run.

    Three stacked bar-chart rows, one column per compound, showing how
    the raw relaxation data becomes the affinity ranking step by step:

    - top:    the observed relaxation-rate-like difference between
              conditions, before any CSA correction (``ΔR₂(obs)`` for
              CSAR — Eq. 8; the analogous log-intensity-ratio term for
              FastCSAR — Eq. 11's numerator).
    - middle: the calculated normalization term used to divide it out
              (``ΔR₂,CSA,b (calc)`` for CSAR — Eq. 8 denominator;
              ``R₂,b (calc)`` = R₂,DD,b + R₂,CSA,b for FastCSAR, since
              FastCSAR does not separate dipolar from CSA — see
              "Simplifications of the process: FastCSAR" in the paper).
    - bottom: the resulting fraction-bound estimate (``p_b × 100``)
              used for ranking.

    Only meaningful for ``workflow in ("CSAR", "FastCSAR")`` — these are
    the two workflows that isolate CSA this way; ``titration`` and
    ``reporter`` derive affinity differently and have their own
    dedicated figures.

    Parameters
    ----------
    result : WorkflowResult
        Must have been produced by :func:`workflow_CSAR` or
        :func:`workflow_FastCSAR` (so ``R2_raw`` carries the
        intermediate quantities this function plots) and have
        ``pb_estimates`` populated.
    output_path : str, optional
        If given, save the figure to this path instead of displaying it.
    protein_concentration : float, optional
        Protein concentration in µM; included in the figure title when
        provided, consistent with :func:`plot_ranking`.

    Raises
    ------
    ValueError
        If ``result.workflow`` isn't ``"CSAR"``/``"FastCSAR"``, or
        ``result.R2_raw``/``result.pb_estimates`` are missing the data
        this function needs (e.g. a hand-built ``WorkflowResult``).
    """
    if result.workflow not in ("CSAR", "FastCSAR"):
        raise ValueError(
            "plot_CSA_isolation only applies to CSAR/FastCSAR results "
            f"(got workflow={result.workflow!r})."
        )
    calc_key = "dR2CSA_calc" if result.workflow == "CSAR" else "R2b_calc"
    if (result.R2_raw is None or "dR2_obs" not in result.R2_raw
            or calc_key not in result.R2_raw or result.pb_estimates is None):
        raise ValueError(
            "result.R2_raw/pb_estimates is missing the data plot_CSA_isolation "
            "needs — was this WorkflowResult produced by workflow_CSAR/"
            "workflow_FastCSAR (not hand-built)?"
        )

    names = result.compound_names
    n = len(names)
    dR2_obs = np.asarray(result.R2_raw["dR2_obs"], dtype=float)
    R2_calc = np.asarray(result.R2_raw[calc_key], dtype=float)
    pb_pct  = 100.0 * np.asarray(result.pb_estimates, dtype=float)
    calc_label = r"$\Delta R_{2,CSA,b}$ (calc) / s$^{-1}$" if result.workflow == "CSAR" \
        else r"$R_{2,b}$ (calc) / s$^{-1}$"
    obs_label = r"$\Delta R_2$(obs) / s$^{-1}$" if result.workflow == "CSAR" \
        else r"implied $\Delta R_2$(obs) / s$^{-1}$"

    x = np.arange(n)
    fig, axes = plt.subplots(3, 1, figsize=(max(6, 0.7 * n + 2), 8), sharex=True)

    axes[0].bar(x, dR2_obs, color="#a8c6e8", edgecolor="0.4", linewidth=0.6)
    axes[0].set_ylabel(obs_label, fontsize=9)
    axes[0].axhline(0, color="0.6", linewidth=0.8)

    axes[1].bar(x, R2_calc, color="#a8c6e8", edgecolor="firebrick", linewidth=1.3)
    axes[1].set_ylabel(calc_label, fontsize=9)

    axes[2].bar(x, pb_pct, color="darkorange", edgecolor="0.4", linewidth=0.6)
    axes[2].set_ylabel(r"$p_b \times 100$", fontsize=9)

    for ax in axes:
        ax.spines[["top", "right"]].set_visible(False)

    axes[-1].set_xticks(x)
    axes[-1].set_xticklabels(names, rotation=45, ha="right", fontsize=8)

    title = f"{result.workflow}: isolation of CSA effect (Fig. 4c-style, Rüdisser 2020)"
    if protein_concentration is not None:
        title += f"  ([Protein] = {protein_concentration:.6g} µM)"
    fig.suptitle(title, fontsize=10, fontweight="bold")
    fig.tight_layout(rect=[0, 0, 1, 0.96])

    if output_path:
        fig.savefig(output_path, dpi=150, bbox_inches="tight")
        print(f"[plot] Saved CSA-isolation diagnostic to {output_path}")
    else:
        plt.show()
    plt.close(fig)


def print_ranking_table(result: WorkflowResult) -> None:
    """Print a formatted ranking table to stdout."""
    order = np.argsort(result.scores)[::-1]
    has_err = (result.pb_uncertainties is not None and
               np.any(np.isfinite(result.pb_uncertainties)))
    header = f"{'Rank':>4}  {'Compound':<20}  {'Score':>8}"
    if result.pb_estimates is not None:
        header += f"  {'p_b (%)':>8}"
    if has_err:
        header += f"  {'± (%)':>7}"
    if result.KD_estimates is not None:
        header += f"  {'KD':>10}"
    if result.KD_uncertainties is not None:
        header += f"  {'KD err':>10}"
    print(f"\n{'='*len(header)}")
    print(f"  {result.workflow} ranking")
    print(f"{'='*len(header)}")
    print(header)
    print("-" * len(header))
    for rank, i in enumerate(order, 1):
        line = f"{rank:>4}  {result.compound_names[i]:<20}  {result.scores[i]:>8.4f}"
        if result.pb_estimates is not None:
            line += f"  {result.pb_estimates[i]*100:>7.2f}%"
        if has_err:
            sig = result.pb_uncertainties[i]
            line += f"  {sig*100:>6.2f}%" if np.isfinite(sig) else f"  {'N/A':>6}"
        if result.KD_estimates is not None:
            kd = result.KD_estimates[i]
            line += f"  {_format_KD(kd):>10}" if not np.isnan(kd) else f"  {'N/A':>10}"
        if result.KD_uncertainties is not None:
            kd_err = result.KD_uncertainties[i]
            line += f"  {kd_err:>10.2f}" if not np.isnan(kd_err) else f"  {'N/A':>10}"
        print(line)
    print("=" * len(header))
    if result.notes:
        for note in result.notes:
            print(f"  Note: {note}")
    print()


