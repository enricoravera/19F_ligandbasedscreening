def _parse_compound(name: str, cfg: dict) -> CompoundData:
    """Build a CompoundData from a ``[compound.NAME]`` config block.

    R2 values live in a ``[compound.NAME.R2]`` sub-table whose keys are the
    magnetic field strength in Tesla (as a quoted string, e.g. ``"16.4"``).
    Values are either:

    * ``[R2_free, R2_protein]``  — two-element list for CSAR / FastCSAR
    * ``[R2_0, R2_1, ...]``      — one value per protein concentration for titration

    R2_err values (1σ uncertainties) live in ``[compound.NAME.R2_err]``, keyed
    the same way.  The disambiguation mirrors R2:

    * ``[σ_free, σ_protein]``  — exactly two elements → stored as a 2-tuple
      (CSAR / FastCSAR behaviour, unchanged)
    * ``[σ_P0, σ_P1, ...]``    — any other length → stored as a list, one
      σ per protein concentration (titration)

    FastCSAR can alternatively be driven off raw delay/intensity arrays
    instead of a pre-fitted R2 — those live in a separate
    ``[compound.NAME.relaxation_data]`` sub-table (as written by
    ``populate_config.py``'s fastcsar "raw" output mode), keyed the same
    way by field strength, with each entry an inline table of
    ``delays_free``, ``delays_protein``, ``intensity_free``, and
    ``intensity_protein`` arrays.
    """
    c = CompoundData(
        name=name,
        fluorine_type=cfg.get("fluorine_type", "CF3"),
        delta_sigma=float(cfg["delta_sigma"]),
        eta=float(cfg.get("eta", 0.0)),
    )
    # R2 sub-table: keys are field strengths in Tesla (strings)
    for B_str, val in cfg.get("R2", {}).items():
        B = float(B_str)
        if isinstance(val, list) and len(val) == 2:
            c.R2_fitted[B] = (float(val[0]), float(val[1]))
        elif isinstance(val, list):
            # Titration: one R2 per protein concentration
            c.R2_fitted[B] = [float(v) for v in val]
    # R2_err sub-table: 1σ uncertainties, same structure as R2.
    # len==2  → 2-tuple (σ_free, σ_protein) for CSAR / FastCSAR.
    # len!=2  → list [σ_P0, σ_P1, …] for titration (one per concentration).
    # This mirrors the identical disambiguation used above for R2, and is
    # intentional: a titration with exactly 2 protein concentrations cannot
    # be distinguished from a free/protein pair — use ≥ 3 concentrations.
    for B_str, val in cfg.get("R2_err", {}).items():
        B = float(B_str)
        if isinstance(val, list) and len(val) == 2:
            c.R2_err[B] = (float(val[0]), float(val[1]))
        elif isinstance(val, list):
            # Titration: one σ_R2 per protein concentration
            c.R2_err[B] = [float(v) for v in val]
    # relaxation_data sub-table: raw delay/intensity arrays for FastCSAR's
    # point-ratio path (used when no R2 was fitted for this field). Each
    # entry stores delays_free and delays_protein separately, but
    # workflow_FastCSAR indexes I_free/I_prot off one shared `delays`
    # array (Eq. 11 assumes both conditions were sampled at the same
    # delay points), so delays_free is used as that array, falling back
    # to delays_protein if the free-ligand series is missing.
    for B_str, val in cfg.get("relaxation_data", {}).items():
        B = float(B_str)
        delays_free       = [float(x) for x in val.get("delays_free", [])]
        delays_protein    = [float(x) for x in val.get("delays_protein", [])]
        intensity_free    = [float(x) for x in val.get("intensity_free", [])]
        intensity_protein = [float(x) for x in val.get("intensity_protein", [])]
        delays = delays_free or delays_protein
        c.relaxation_data[B] = (
            np.array(delays),
            np.array(intensity_free),
            np.array(intensity_protein),
        )
    # Optional: reporter signal
    if "reporter_signal_plus" in cfg:
        c.reporter_signal_plus = float(cfg["reporter_signal_plus"])
    if "reporter_signal_minus" in cfg:
        c.reporter_signal_minus = float(cfg["reporter_signal_minus"])
    return c


def _sanitize_dirname(name: str) -> str:
    """
    Turn an arbitrary protein name into a filesystem-safe directory
    component: whitespace → underscore, anything else that isn't
    alphanumeric/underscore/hyphen stripped out.

    Must produce the *identical* string ``populate_config.py``'s own
    ``_sanitize_dirname`` produces for the same ``protein_name`` — that
    script writes each compound's per-field fit results under
    ``fit_results/{protein_name}/``, and this workflow's ranking plot
    needs to land in that same directory rather than a differently-named
    one.
    """
    safe = re.sub(r"\s+", "_", name.strip())
    safe = re.sub(r"[^A-Za-z0-9_-]", "", safe)
    return safe or "protein"


def _format_conc_dir(conc: float) -> str:
    """
    Format a protein concentration (µM) into a filesystem-safe directory
    name fragment, e.g. ``10.0 → '10uM'``, ``10.5 → '10p5uM'``.

    Must produce the *identical* string as ``populate_config.py``'s own
    ``_format_conc_dir`` — both helpers are kept in sync deliberately.
    """
    return f"{conc:g}".replace(".", "p") + "uM"


def _format_field_dir(field_T) -> str:
    """
    Format one or more magnetic field values (Tesla) into a
    filesystem-safe directory-name fragment, e.g. ``16.4 → '16p4T'``.

    ``csar`` runs at two field points (``B_high``/``B_low``) — pass a
    ``(B_high, B_low)`` pair (or any iterable of floats) to get them
    combined into a single fragment, highest first, e.g.
    ``(16.4, 28.2) → '28p2T_16p4T'``.

    Must produce the *identical* string as ``populate_config.py``'s own
    ``_format_field_dir`` — both helpers are kept in sync deliberately.
    """
    if isinstance(field_T, (list, tuple)):
        parts = sorted((float(b) for b in field_T), reverse=True)
        return "_".join(_format_field_dir(b) for b in parts)
    return f"{float(field_T):g}".replace(".", "p") + "T"


def _basedir(
    protein_name: Optional[str],
    protein_concentration: Optional[float] = None,
    run_field: Optional[object] = None,
) -> Path:
    """
    Return the ``fit_results`` directory to save results into,
    namespaced by protein name when one is known, further by protein
    concentration for ``csar``/``fastcsar`` workflows, and further still
    by the magnetic field(s) used for the whole run — a single float for
    fastcsar/titration, or a ``(B_high, B_low)`` pair for csar (see
    :func:`_format_field_dir`).

    Mirrors ``populate_config.py``'s ``_basedir`` exactly (see its
    docstring). Creates the directory if it doesn't exist yet.
    """
    basedir = Path("fit_results")
    if protein_name:
        basedir = basedir / _sanitize_dirname(protein_name)
    if protein_concentration is not None:
        basedir = basedir / _format_conc_dir(protein_concentration)
    if run_field is not None:
        basedir = basedir / _format_field_dir(run_field)
    basedir.mkdir(parents=True, exist_ok=True)
    return basedir


def run_from_config(config_path: str) -> WorkflowResult:
    """
    Parse a TOML config file and run the specified workflow.

    Parameters
    ----------
    config_path : str
        Path to the ``.toml`` configuration file.

    Returns
    -------
    WorkflowResult
    """
    with open(config_path, "rb") as fh:
        cfg = tomllib.load(fh)

    wf_cfg       = cfg["workflow"]
    wf_name      = wf_cfg["name"].lower()
    nucleus      = wf_cfg.get("nucleus", "19F")
    tau_c        = float(wf_cfg.get("tau_c", 10e-9))
    MW_kDa       = float(wf_cfg.get("protein_MW_kDa", 23.0))
    plot_out     = wf_cfg.get("plot_output", None)
    protein_name = wf_cfg.get("protein_name", None)
    # Protein concentration for csar/fastcsar — embedded in the output
    # directory name and used for figure titles.  None for other workflows.
    protein_concentration: Optional[float] = (
        float(wf_cfg["protein_concentration"])
        if wf_name in ("csar", "fastcsar") and "protein_concentration" in wf_cfg
        else None
    )
    # Magnetic field(s) for the whole run, embedded in the output
    # directory (see _basedir/_format_field_dir) — a (B_high, B_low)
    # pair for csar, a single B for fastcsar/titration, None for
    # reporter. Read from the same [workflow] keys populate_config.py's
    # run_fitting reads, so both scripts land on the same directory.
    run_field: Optional[object] = None
    if wf_name == "csar" and "B_high" in wf_cfg and "B_low" in wf_cfg:
        run_field = (float(wf_cfg["B_high"]), float(wf_cfg["B_low"]))
    elif wf_name in ("fastcsar", "titration") and "B" in wf_cfg:
        run_field = float(wf_cfg["B"])

    compounds = [
        _parse_compound(name, comp_cfg)
        for name, comp_cfg in cfg.get("compound", {}).items()
    ]

    if wf_name == "csar":
        B_high = float(wf_cfg["B_high"])
        B_low  = float(wf_cfg["B_low"])
        result = workflow_CSAR(compounds, B_high, B_low, tau_c, nucleus, MW_kDa)

    elif wf_name == "fastcsar":
        B       = float(wf_cfg["B"])
        t_short = float(wf_cfg.get("t_short", 5e-3))
        t_long  = float(wf_cfg.get("t_long", 200e-3))
        result  = workflow_FastCSAR(compounds, B, tau_c, t_short, t_long, nucleus, MW_kDa)

    elif wf_name == "reporter":
        rep_cfg  = cfg["reporter"]
        result   = workflow_reporter(
            reporter_name          = rep_cfg["name"],
            reporter_signal_free   = float(rep_cfg["signal_free"]),
            reporter_signal_protein= float(rep_cfg["signal_protein"]),
            compounds              = compounds,
        )

    elif wf_name == "titration":
        prot_conc = np.array(wf_cfg["protein_concentrations"], dtype=float)
        lig_conc  = float(wf_cfg["ligand_concentration"])
        fit_KD    = bool(wf_cfg.get("fit_KD", False))
        fit_R2free = bool(wf_cfg.get("fit_R2free", False))
        n_sites   = int(wf_cfg.get("n_sites", 1))
        exp_type  = str(wf_cfg.get("experiment_type", "s"))
        B         = float(wf_cfg["B"])
        result    = workflow_titration(
            compounds, B, prot_conc, lig_conc, tau_c, nucleus,
            n_sites=n_sites,
            fit_KD=fit_KD,
            fit_R2free=fit_R2free,
            protein_name=protein_name,
            protein_MW_kDa=MW_kDa,
            experiment_type=exp_type,
        )

    else:
        raise ValueError(
            f"Unknown workflow '{wf_name}'. Choose: csar, fastcsar, reporter, titration."
        )

    print_ranking_table(result)
    if plot_out:
        # Save alongside populate_config.py's per-compound fit_results/
        # {protein_name}/ figures rather than wherever the process
        # happens to be running from — same directory, same naming
        # convention, one place to look for every plot from this run.
        run_basedir = _basedir(protein_name, protein_concentration, run_field)
        plot_out = run_basedir / Path(plot_out).name
        plot_ranking(result, output_path=plot_out, protein_concentration=protein_concentration)
        if wf_name in ("csar", "fastcsar"):
            # Fig. 4c-style diagnostic (Rüdisser 2020) — only meaningful
            # for the two workflows that isolate CSA this way.
            csa_iso_path = run_basedir / f"{Path(plot_out).stem}_CSA_isolation.png"
            plot_CSA_isolation(
                result, output_path=csa_iso_path,
                protein_concentration=protein_concentration,
            )
    else:
        plot_ranking(result, protein_concentration=protein_concentration)
        if wf_name in ("csar", "fastcsar"):
            plot_CSA_isolation(result, protein_concentration=protein_concentration)

    return result


