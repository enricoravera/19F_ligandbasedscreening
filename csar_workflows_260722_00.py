"""
csar_workflows.py
=================
Config-driven workflows for affinity ranking of fluorinated ligands by 19F NMR,
implementing the CSAR and FastCSAR methods described in:

    Rüdisser et al., J. Biomol. NMR 74, 579–594 (2020).
    https://doi.org/10.1007/s10858-020-00325-x

Four workflows are available, selected by the ``[workflow]`` section of a TOML
configuration file:

    csar        – two-field spin-lock pipeline (full CSAR)
    fastcsar    – single-field simplified ranking (FastCSAR)
    reporter    – displacement of a known reporter ligand
    titration   – exchange-suppressed ligand-observed titration

Usage
-----
    python csar_workflows.py experiment.toml

or from Python::

    from csar_workflows import run_from_config
    results = run_from_config("experiment.toml")

Config file format
------------------
See ``example_config.toml`` (generated by running this script without arguments).
"""

