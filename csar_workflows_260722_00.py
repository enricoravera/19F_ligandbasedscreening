@dataclass
class CompoundData:
    """All per-compound information needed across workflows."""
    name: str
    fluorine_type: str          # 'CF3' or 'CF'
    # CSA parameters (reduced anisotropy and asymmetry, as in Fig. 2)
    delta_sigma: float          # ppm
    eta: float
    # Relaxation data: dict mapping field (T) -> (delays_s, intensities_free, intensities_protein)
    relaxation_data: Dict[float, Tuple[np.ndarray, np.ndarray, np.ndarray]] = field(default_factory=dict)
    # Pre-fitted R2 values: dict mapping field -> (R2_free, R2_protein)
    R2_fitted: Dict[float, Tuple[float, float]] = field(default_factory=dict)
    # 1σ uncertainties on R2_fitted, same keys: (σ_R2_free, σ_R2_protein)
    # nan entries mean the uncertainty was not estimated.
    R2_err: Dict[float, Tuple[float, float]] = field(default_factory=dict)
    # For reporter workflow: reporter signal intensity (−protein, +protein)
    reporter_signal_minus: Optional[float] = None
    reporter_signal_plus: Optional[float] = None


@dataclass
class WorkflowResult:
    """Unified output from any workflow."""
    workflow: str
    compound_names: List[str]
    scores: np.ndarray          # higher = stronger binder
    pb_estimates: Optional[np.ndarray] = None
    pb_uncertainties: Optional[np.ndarray] = None  # 1σ on p_b, same order as scores
    KD_estimates: Optional[np.ndarray] = None   # µM, if available
    R2_raw: Optional[Dict] = None
    notes: List[str] = field(default_factory=list)


# ============================================================================
# Workflow 1: CSAR (two-field spin-lock, full pipeline)
# ============================================================================

def workflow_CSAR(
    compounds: List[CompoundData],
    B_high: float,
    B_low: float,
    tau_c: float,
    nucleus: str = "19F",
    protein_MW_kDa: float = 23.0,
) -> WorkflowResult:
    """
    Full CSAR pipeline (Section "Results", Rüdisser 2020).

    Steps
    -----
    1. Obtain R₂ at two fields under spin-lock (exchange suppressed).
    2. Subtract low-field from high-field → ΔR₂ ≈ p_b · 0.49 · R₂,CSA,b,high
       (Eqs. 7–8; the factor 0.49 = 1 − (B_low/B_high)² for the two fields
       11.75 T and 16.4 T used in the paper; generalised here).
    3. Divide ΔR₂ by the calculated Δ(R₂,CSA,b) to get p_b.

    Parameters
    ----------
    compounds : list of CompoundData
        Each compound must have R2_fitted populated for both B_high and B_low.
    B_high, B_low : float
        Magnetic fields in Tesla.
    tau_c : float
        Rotational correlation time of the protein–ligand complex (s).
    nucleus : str
        Observed nucleus.
    protein_MW_kDa : float
        Protein molecular weight, used only for documentation / RDD estimate.

    Returns
    -------
    WorkflowResult
    """
    names, pb_list, sigma_pb_list = [], [], []
    dR2_obs_list, R2CSA_calc_list = [], []

    # ΔR₂,CSA,b = R₂,CSA,b(high) − R₂,CSA,b(low)  (Eq. 8)
    # ≈ R₂,CSA,b(high) · (1 − (B_low/B_high)²)    by B² scaling
    field_ratio_sq = (B_low / B_high) ** 2

    notes = []
    for c in compounds:
        if B_high not in c.R2_fitted or B_low not in c.R2_fitted:
            warnings.warn(f"Compound {c.name}: missing R2 data for one or both fields — skipping.")
            continue

        R2_f_high, R2_p_high = c.R2_fitted[B_high]
        R2_f_low,  R2_p_low  = c.R2_fitted[B_low]

        # Step 1: subtract free-ligand contribution (Eq. 7 full form)
        dR2_obs = (R2_p_high - R2_f_high) - (R2_p_low - R2_f_low)

        # Step 2: calculate R₂,CSA,b at high field
        R2CSA_high = R2_CSA_bound(c.delta_sigma, c.eta, B_high, tau_c, nucleus)
        dR2CSA_calc = R2CSA_high * (1.0 - field_ratio_sq)

        # Step 3: p_b estimate (Eq. 9)
        if dR2CSA_calc <= 0:
            warnings.warn(f"Compound {c.name}: calculated ΔR₂,CSA ≤ 0 — check tensor parameters.")
            pb = 0.0
        else:
            pb = max(dR2_obs / dR2CSA_calc, 0.0)

        # Uncertainty propagation (Eq. 7): ΔR₂ = ΔR₂_high - ΔR₂_low
        #   σ²_ΔR₂ = σ²_p_high + σ²_f_high + σ²_p_low + σ²_f_low
        #   σ_p_b  = σ_ΔR₂ / ΔR₂_CSA_calc  (calculated CSA has no fit uncertainty)
        err_high  = c.R2_err.get(B_high, (np.nan, np.nan))
        err_low   = c.R2_err.get(B_low,  (np.nan, np.nan))
        err_terms = [err_high[1], err_high[0], err_low[1], err_low[0]]
        if all(not np.isfinite(e) for e in err_terms):
            sigma_dR2 = np.nan     # no errors available for this compound
        else:
            sigma_dR2 = np.sqrt(np.nansum([e**2 for e in err_terms]))
        sigma_pb = (sigma_dR2 / dR2CSA_calc
                    if (dR2CSA_calc > 0 and np.isfinite(sigma_dR2))
                    else np.nan)

        names.append(c.name)
        pb_list.append(pb)
        sigma_pb_list.append(sigma_pb)
        dR2_obs_list.append(dR2_obs)
        R2CSA_calc_list.append(dR2CSA_calc)

    pb_arr = np.array(pb_list)
    if len(pb_arr) == 0:
        raise ValueError("No compounds with data at both fields. Check R2_fitted keys.")
    # Normalise to [0, 1] relative to the strongest binder for ranking
    pb_max = pb_arr.max() if pb_arr.max() > 0 else 1.0
    scores = pb_arr / pb_max

    notes.append(
        f"B_high={B_high} T, B_low={B_low} T, τ_c={tau_c:.2e} s; "
        f"field factor (1−(B_low/B_high)²) = {1-field_ratio_sq:.4f}"
    )

    sigma_pb_arr = np.array(sigma_pb_list)
    return WorkflowResult(
        workflow="CSAR",
        compound_names=names,
        scores=scores,
        pb_estimates=pb_arr,
        pb_uncertainties=sigma_pb_arr / pb_max,   # normalised like scores
        R2_raw={"dR2_obs": dR2_obs_list, "dR2CSA_calc": R2CSA_calc_list,
                "sigma_dR2": sigma_pb_list},
        notes=notes,
    )


# ============================================================================
# Workflow 2: FastCSAR (single-field, Eq. 11)
# ============================================================================

def workflow_FastCSAR(
    compounds: List[CompoundData],
    B: float,
    tau_c: float,
    t_short: float,
    t_long: float,
    nucleus: str = "19F",
    protein_MW_kDa: float = 23.0,
) -> WorkflowResult:
    """
    Simplified FastCSAR ranking (Eq. 11, Rüdisser 2020).

    Uses two time-points from a single spin-lock experiment at one field.
    Signal decay ratio corrected for free-ligand relaxation and normalised
    by calculated R₂,b = R₂,DD,b + R₂,CSA,b.

    Parameters
    ----------
    compounds : list of CompoundData
        Each compound must have relaxation_data populated for field B with
        arrays of at least two delays that bracket t_short and t_long, OR
        have R2_fitted[B] populated directly (in which case t_short/t_long
        are used only to compute the effective decay ratio analytically).
    B : float
        Magnetic field in Tesla.
    tau_c : float
        Rotational correlation time of the complex (s).
    t_short, t_long : float
        Two spin-lock delays in seconds used to estimate signal decay.
        Typically 5 ms and 200 ms (CF₃) or 100 ms (CF).
    nucleus : str
        Observed nucleus.
    protein_MW_kDa : float
        Protein molecular weight (kDa) — used to estimate R₂,DD,b via the
        rule-of-thumb R_DD ≈ MW [kDa⁻¹ s⁻¹] (paper's approximation).

    Returns
    -------
    WorkflowResult
    """
    # Rule-of-thumb dipolar contribution (bound state, paper p. 586)
    R2_DD_b = protein_MW_kDa          # s⁻¹ · kDa⁻¹ · kDa = s⁻¹

    names, pb_list, sigma_pb_list = [], [], []
    notes = []

    for c in compounds:
        # --- get I(t_short) and I(t_long) in the presence and absence of protein
        sigma_lnterm = np.nan   # propagated fit uncertainty on the log-ratio
        if B in c.relaxation_data:
            delays, I_free, I_prot = c.relaxation_data[B]
            delays = np.asarray(delays)
            I_free = np.asarray(I_free)
            I_prot = np.asarray(I_prot)
            # Interpolate or find nearest time-points
            idx_s = int(np.argmin(np.abs(delays - t_short)))
            idx_l = int(np.argmin(np.abs(delays - t_long)))
            It_free_s = I_free[idx_s]; It_free_l = I_free[idx_l]
            It_prot_s = I_prot[idx_s]; It_prot_l = I_prot[idx_l]
            I0_free = I_free[0];      I0_prot = I_prot[0]
            # Use long time-point as described in the paper
            # ln(I(t)_p/I(0)_p  /  I(t)_f/I(0)_f) / (R2_b · t)
            ratio_p = It_prot_l / I0_prot if I0_prot > 0 else 1e-9
            ratio_f = It_free_l / I0_free if I0_free > 0 else 1e-9
            lnterm = np.log(max(ratio_p / ratio_f, 1e-9))
        elif B in c.R2_fitted and isinstance(c.R2_fitted[B], tuple):
            # Analytical path: simulate signal decay ratio from fitted R2 values.
            # ln(I(t)_p/I(0)_p / I(t)_f/I(0)_f) = -(R2_prot - R2_free) * t  (negative)
            R2_free, R2_prot = c.R2_fitted[B]
            lnterm = -(R2_prot - R2_free) * t_long   # negative → p_b positive after negation
            # σ_lnterm = t_long × √(σ_R2_prot² + σ_R2_free²)
            err = c.R2_err.get(B, (np.nan, np.nan))
            err_terms_fc = [err[1], err[0]]  # [σ_prot, σ_free]
            if all(not np.isfinite(e) for e in err_terms_fc):
                sigma_lnterm = np.nan
            else:
                sigma_lnterm = t_long * np.sqrt(np.nansum([e**2 for e in err_terms_fc]))
        else:
            warnings.warn(f"Compound {c.name}: no data at B={B} T — skipping.")
            continue

        # R₂,b = R₂,DD,b + R₂,CSA,b  (Eq. 5 + rule of thumb)
        R2_CSA_b = R2_CSA_bound(c.delta_sigma, c.eta, B, tau_c, nucleus)
        R2_b = R2_DD_b + R2_CSA_b

        t_eff = t_long
        # lnterm is negative (signal decays), so negate to get positive p_b (Eq. 11)
        pb = -lnterm / (R2_b * t_eff) if (R2_b * t_eff) != 0 else 0.0
        pb = max(pb, 0.0)
        # σ_p_b = σ_lnterm / (R2_b × t_long)
        sigma_pb = (sigma_lnterm / (R2_b * t_eff)
                    if (np.isfinite(sigma_lnterm) and R2_b * t_eff != 0)
                    else np.nan)

        names.append(c.name)
        pb_list.append(pb)
        sigma_pb_list.append(sigma_pb)

    pb_arr = np.array(pb_list)
    pb_max = pb_arr.max() if pb_arr.max() > 0 else 1.0
    scores = pb_arr / pb_max

    notes.append(
        f"B={B} T, τ_c={tau_c:.2e} s, t_long={t_long*1e3:.0f} ms, "
        f"R₂,DD,b ≈ {R2_DD_b:.1f} s⁻¹ (MW rule-of-thumb)"
    )

    sigma_pb_arr = np.array(sigma_pb_list)
    return WorkflowResult(
        workflow="FastCSAR",
        compound_names=names,
        scores=scores,
        pb_estimates=pb_arr,
        pb_uncertainties=sigma_pb_arr / pb_max,
        notes=notes,
    )


# ============================================================================
# Workflow 3: Reporter assay
# ============================================================================

def workflow_reporter(
    reporter_name: str,
    reporter_signal_free: float,
    reporter_signal_protein: float,
    compounds: List[CompoundData],
) -> WorkflowResult:
    """
    Reporter assay affinity ranking (Fig. 7, Rüdisser 2020).

    The reporter signal is measured in the presence of each test compound.
    Displacement of the reporter is proportional to relative binding affinity.

    Parameters
    ----------
    reporter_name : str
        Name of the reporter ligand.
    reporter_signal_free : float
        Intensity of the reporter signal WITHOUT protein.
    reporter_signal_protein : float
        Intensity of the reporter signal WITH protein (no competitor).
    compounds : list of CompoundData
        Each compound must have ``reporter_signal_plus`` set to the
        intensity of the reporter in the presence of BOTH protein and that
        compound.  ``reporter_signal_minus`` is unused here.

    Returns
    -------
    WorkflowResult
        ``scores`` encodes degree of displacement (higher = stronger binder).
    """
    # Reference: fractional reporter signal in presence of protein (no competitor)
    I_ref = reporter_signal_protein / reporter_signal_free  # ~0.2 in the paper

    names, scores_list = [], []
    for c in compounds:
        if c.reporter_signal_plus is None:
            warnings.warn(f"Compound {c.name}: reporter_signal_plus not set — skipping.")
            continue
        I_comp = c.reporter_signal_plus / reporter_signal_free
        # Displacement = how much the reporter recovers toward the free signal
        # 0 = no displacement (same as with protein only), 1 = full displacement
        displacement = max((I_comp - I_ref) / (1.0 - I_ref), 0.0)
        names.append(c.name)
        scores_list.append(displacement)

    scores = np.array(scores_list)
    s_max = scores.max() if scores.max() > 0 else 1.0

    notes = [
        f"Reporter: {reporter_name}, I_free={reporter_signal_free:.3f}, "
        f"I_protein={reporter_signal_protein:.3f} (fraction={I_ref:.3f})"
    ]
    return WorkflowResult(
        workflow="Reporter",
        compound_names=names,
        scores=scores / s_max,
        notes=notes,
    )


# ============================================================================
# Workflow 4: Exchange-suppressed ligand-observed titration (Eq. 12)
# ============================================================================

def workflow_titration(
    compounds: List[CompoundData],
    B: float,
    protein_concentrations: np.ndarray,
    ligand_concentration: float,
    tau_c: float,
    nucleus: str = "19F",
    n_sites: int = 1,
    fit_KD: bool = False,
) -> WorkflowResult:
    """
    Exchange-suppressed ligand-observed titration (Fig. 8, Rüdisser 2020).

    Each compound in ``compounds`` must have relaxation_data[B] set as a
    2-D array: rows = protein concentrations (same order as
    ``protein_concentrations``), columns = (delays, intensities).
    Alternatively, if R2_fitted[B] is a list of (R2_free, R2_prot) tuples
    per protein concentration, those are used directly.

    Parameters
    ----------
    compounds : list of CompoundData
        relaxation_data[B] should be a list of (delays, intensities) arrays,
        one per protein concentration.  Or R2_fitted[B] = list of R2 values
        at each [P].
    B : float
        Magnetic field in Tesla.
    protein_concentrations : array-like
        Protein concentrations in µM (same order as data in each compound).
    ligand_concentration : float
        Total ligand concentration in µM.
    tau_c : float
        Rotational correlation time of the complex (s).
    nucleus : str
        Observed nucleus.
    n_sites : int
        Number of equivalent binding sites (default 1).
    fit_KD : bool
        If True, attempt to fit KD from Eq. 12.  This is ill-conditioned
        for weak binders (see Discussion) — a warning is emitted.

    Returns
    -------
    WorkflowResult
        ``scores`` = slope of R₂ vs [P] (normalised).
        ``KD_estimates`` = fitted KD in µM if fit_KD=True, else None.
    """
    prot_arr = np.asarray(protein_concentrations, dtype=float)  # µM
    L_tot = ligand_concentration   # µM

    names, slopes, KD_fits = [], [], []
    notes = []

    for c in compounds:
        # Collect R2 values at each protein concentration
        if isinstance(c.R2_fitted.get(B), list):
            R2_vals = np.array([r for r in c.R2_fitted[B]], dtype=float)
        elif B in c.relaxation_data and isinstance(c.relaxation_data[B], list):
            R2_vals = []
            for delays_i, intensities_i in c.relaxation_data[B]:
                r2_i, _ = fit_monoexponential(np.asarray(delays_i), np.asarray(intensities_i))
                R2_vals.append(r2_i)
            R2_vals = np.array(R2_vals)
        else:
            warnings.warn(f"Compound {c.name}: titration data not found — skipping.")
            continue

        R2_free = R2_vals[0] if prot_arr[0] == 0.0 else R2_vals.min()

        # --- Ranking by slope (R2 / [P]) as in the paper ---
        # Use simple linear regression of R2 vs [P] for robustness
        slope, _ = np.polyfit(prot_arr, R2_vals, 1)
        names.append(c.name)
        slopes.append(slope)

        if fit_KD:
            # Eq. 12:  R2_SL = R2_f + n·[P]_tot·(R2_b − R2_f) / (KD + [L]_f) · [L]_f/[L]_tot
            # Simplified assuming [L]_f ≈ [L]_tot (p_b << 1)
            def titration_eq(P_tot, KD, R2_b):
                Lf = L_tot  # approximation
                return R2_free + n_sites * P_tot * (R2_b - R2_free) / (KD + Lf)
            try:
                popt, pcov = curve_fit(
                    titration_eq, prot_arr, R2_vals,
                    p0=[500.0, R2_free * 10],
                    bounds=([0.01, R2_free], [1e5, R2_free * 1000]),
                    maxfev=10000,
                )
                KD_fits.append(popt[0])
            except RuntimeError:
                KD_fits.append(np.nan)
                notes.append(f"KD fit did not converge for {c.name}.")

    slopes_arr = np.array(slopes)
    s_max = slopes_arr.max() if slopes_arr.max() > 0 else 1.0
    scores = slopes_arr / s_max

    if fit_KD:
        warnings.warn(
            "KD fitting from ligand-observed titrations is ill-conditioned "
            "for weak binders (large KD/R2_b co-variance). "
            "Use slope ranking as primary output.",
            UserWarning,
        )
        notes.append(
            "KD values carry large uncertainty (see Rüdisser 2020, Discussion)."
        )

    return WorkflowResult(
        workflow="Titration",
        compound_names=names,
        scores=scores,
        KD_estimates=np.array(KD_fits) if KD_fits else None,
        notes=notes,
    )


