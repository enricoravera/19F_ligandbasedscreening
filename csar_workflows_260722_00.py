# ============================================================================
# Physical / NMR helper functions
# ============================================================================

def gamma_rad(nucleus: str) -> float:
    """Gyromagnetic ratio in rad s⁻¹ T⁻¹."""
    return _GAMMA[nucleus] * 2 * np.pi * 1e6


def spectral_density_iso(omega: float, tau: float) -> float:
    """Isotropic Lorentzian spectral density  J(ω) = τ / (1 + ω²τ²)."""
    return tau / (1.0 + (omega * tau) ** 2)


def R2_CSA_bound(
    delta_sigma_ppm: float,
    eta: float,
    B0: float,
    tau_c: float,
    nucleus: str = "19F",
) -> float:
    """
    Transverse CSA relaxation rate in the bound state (Eq. 5, Rüdisser 2020).

    Parameters
    ----------
    delta_sigma_ppm : float
        Reduced anisotropy δσ in ppm (δσ = σ_zz - σ_iso).
    eta : float
        Axial asymmetry η = (σ_yy - σ_xx) / δσ.
    B0 : float
        Magnetic field in Tesla.
    tau_c : float
        Rotational correlation time of the complex in seconds.
    nucleus : str
        NMR-active nucleus (default ``'19F'``).

    Returns
    -------
    float
        R₂,CSA,b in s⁻¹.

    Notes
    -----
    The formula uses the combined anisotropy parameter
    δσ²(1 + η²/3), which equals Δσ²(1 + η²/3)·(4/9) when converting from
    overall anisotropy Δσ.  Here we work directly with the reduced anisotropy
    δσ (= 2/3 · Δσ) as used throughout the paper.
    """
    delta_sigma = delta_sigma_ppm * 1e-6          # ppm → dimensionless
    gF = gamma_rad(nucleus)
    omegaF = gF * B0
    J0   = spectral_density_iso(0.0,    tau_c)
    JomF = spectral_density_iso(omegaF, tau_c)
    prefactor = (1.0 / 20.0) * gF**2 * B0**2 * delta_sigma**2 * (1.0 + eta**2 / 3.0)
    return prefactor * (4.0 * J0 + 3.0 * JomF)


def R2_CSA_bound_tensor(
    sigma: np.ndarray,
    B0: float,
    tau_c: float,
    nucleus: str = "19F",
) -> float:
    """
    Transverse CSA relaxation using the full 3×3 shielding tensor
    (Eqs. 18–19, Suturina et al. 2018, already used in your CSA_relaxation).

    sigma : 3×3 ndarray in ppm — will be converted to dimensionless internally.
    """
    from fun_hetrelax_models import J, J_omega_tau_iso  # type: ignore
    sigma_d = np.asarray(sigma, dtype=float) / 1e6
    gF = gamma_rad(nucleus)
    omegaF = gF * B0
    tau_params = (tau_c,)
    bigLambda2 = (
        (sigma_d[0, 1] - sigma_d[1, 0]) ** 2
        + (sigma_d[0, 2] - sigma_d[2, 0]) ** 2
        + (sigma_d[1, 2] - sigma_d[2, 1]) ** 2
    )
    bigDelta2 = (
        sigma_d[0, 0] ** 2 + sigma_d[1, 1] ** 2 + sigma_d[2, 2] ** 2
        - sigma_d[0, 0] * sigma_d[1, 1]
        - sigma_d[0, 0] * sigma_d[2, 2]
        - sigma_d[1, 1] * sigma_d[2, 2]
        + 0.75 * (
            (sigma_d[0, 1] + sigma_d[1, 0]) ** 2
            + (sigma_d[0, 2] + sigma_d[2, 0]) ** 2
            + (sigma_d[1, 2] + sigma_d[2, 1]) ** 2
        )
    )
    J0   = J(J_omega_tau_iso, 0,       tau_params)
    JomF = J(J_omega_tau_iso, omegaF,  tau_params)
    J3omF= J(J_omega_tau_iso, 3*omegaF,tau_params)
    R2 = (
        (5.0 / 24.0) * omegaF**2 * bigLambda2 * J3omF
        + (1.0 / 18.0) * omegaF**2 * bigDelta2 * (4.0 * J0 + 3.0 * JomF)
    )
    return R2


def fit_monoexponential(delays: np.ndarray, intensities: np.ndarray) -> Tuple[float, float]:
    """
    Fit I(t) = I0 · exp(−R2 · t) and return (R2, I0).

    Parameters
    ----------
    delays : array-like
        Relaxation delays in seconds.
    intensities : array-like
        Corresponding signal intensities (arbitrary units, positive).

    Returns
    -------
    R2 : float
        Fitted relaxation rate in s⁻¹.
    I0 : float
        Fitted initial intensity.
    """
    delays = np.asarray(delays, dtype=float)
    intensities = np.asarray(intensities, dtype=float)
    def model(t, I0, R2):
        return I0 * np.exp(-R2 * t)
    p0 = (intensities[0], 1.0 / delays[-1])
    popt, _ = curve_fit(model, delays, intensities, p0=p0, maxfev=5000)
    return float(popt[1]), float(popt[0])


